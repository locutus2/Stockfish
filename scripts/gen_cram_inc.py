#!/usr/bin/env python3
# Regenerates src/cram_net.inc (the CRAM net embedded in the binary) from src/model-i8.bin.
# Usage: python3 scripts/gen_cram_inc.py [model.bin] [out.inc]
import sys

src = sys.argv[1] if len(sys.argv) > 1 else "src/model2-i8.bin"
dst = sys.argv[2] if len(sys.argv) > 2 else "src/cram_net.inc"
data = open(src, "rb").read()
with open(dst, "w", newline="\n") as f:
    f.write("// Generated by scripts/gen_cram_inc.py from model-i8.bin. Do not edit.\n")
    for i in range(0, len(data), 24):
        f.write(",".join("0x%02X" % b for b in data[i:i + 24]) + ",\n")
